// Regenerates lib/brand/palettes.js: each title's colours and typeface, read
// from that title's own website theme, for the emails this app sends.
//
//   node scripts/build-brand-palettes.mjs
//
// The website child themes sit beside this repo (../<title>-website/child).
// Set SITES_ROOT to the folder that holds them when running from a worktree.
//
// Why generated rather than written by hand: the newsletter template carried
// Smart SME's blue and Space Grotesk as constants, so every title's newsletter
// went out with Smart SME's links, button and rule under its own masthead. A
// title's email colours now come from the same theme.json its site uses, and
// cannot drift from it.
import fs from "fs";
import path from "path";

const OUT = "lib/brand/palettes.js";
const ROOT = process.env.SITES_ROOT || path.resolve("..");

const TITLES = {
  "smart-sme": "smart-sme-website",
  "fleet-magazine": "fleet-magazine-website",
  "golf-resort-magazine": "golf-resort-magazine-website",
  "barbering-business": "barbering-business-website",
  "airport-business-magazine": "airport-business-magazine-website",
};

const entries = [];
for (const [slug, dir] of Object.entries(TITLES)) {
  const file = path.join(ROOT, dir, "child", "theme.json");
  const json = JSON.parse(fs.readFileSync(file, "utf8"));
  const colour = Object.fromEntries((json.settings?.color?.palette || []).map((c) => [c.slug, c.color]));
  const need = ["brand", "brand-bright", "contrast", "surface", "line", "muted", "muted-light"];
  const gaps = need.filter((k) => !colour[k]);
  if (gaps.length) throw new Error(`${slug}: theme.json has no ${gaps.join(", ")}`);

  // The heading face is the one the masthead and headlines share on the site.
  const families = json.settings?.typography?.fontFamilies || [];
  const heading = families.find((f) => f.slug === "heading") || families.find((f) => f.slug === "brand");
  const font = (heading?.fontFamily || "Arial").split(",")[0].replace(/["']/g, "").trim();

  entries.push(`  "${slug}": {
    brand: "${colour.brand}",
    brandBright: "${colour["brand-bright"]}",
    ink: "${colour.contrast}",
    surface: "${colour.surface}",
    line: "${colour.line}",
    muted: "${colour.muted}",
    mutedLight: "${colour["muted-light"]}",
    white: "#FFFFFF",
    font: "${font}",
    fontCss: "https://fonts.googleapis.com/css2?family=${font.replace(/ /g, "+")}:wght@400;500;700&display=swap",
  },`);
  console.log(`${slug.padEnd(26)} brand ${colour.brand}, ink ${colour.contrast}, ${font}`);
}

fs.writeFileSync(
  OUT,
  `// Each title's email colours and typeface. Generated by
// scripts/build-brand-palettes.mjs from the title's own website theme.json; do
// not edit by hand. Rerun it when a title's site colours change.
export const PALETTES = {
${entries.join("\n")}
};

export function paletteFor(slug) {
  return PALETTES[slug] || null;
}
`
);
console.log(`wrote ${OUT}`);
