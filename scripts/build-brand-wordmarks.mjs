// Regenerates lib/brand/wordmarks.js: two logo cuts per title, embedded in the
// bundle, for the emails this app sends.
//
//   node scripts/build-brand-wordmarks.mjs
//
// Embedded rather than fetched at send time, so a slow or reorganised website
// can never cost an email its branding.
//
// The artwork comes from the brand kit in cogent-base-theme/scripts/brand,
// which builds every title's mark from one spec (September 2026). Build it
// there first:
//
//   cd ../cogent-base-theme/scripts/brand && node build.mjs dist && node email.mjs
//
// The kit is found beside this repo. Set BRAND_KIT to its dist/ folder when
// running from a worktree that is not.
//
// Two cuts, because emails draw a logo two very different ways:
//   png       the one-line mark, drawn 22px high under an outreach sign-off.
//             A stacked mark at that height cannot be read.
//   masthead  the title's main mark, at the top of the weekly newsletter.
//
// Before September 2026 this script typeset each title's CSS lockup itself and
// fetched Smart SME's schema.org logo, which turned out to be its favicon, so
// Smart SME's outreach emails carried a blue square instead of a masthead.
import sharp from "sharp";
import fs from "fs";
import path from "path";

const OUT = "lib/brand/wordmarks.js";
const KIT = process.env.BRAND_KIT || path.resolve("../cogent-base-theme/scripts/brand/dist");

const TITLES = [
  ["smart-sme", "Smart SME"],
  ["fleet-magazine", "The Fleet Magazine"],
  ["golf-resort-magazine", "Golf Resort Magazine"],
  ["barbering-business", "Barbering Business"],
  ["airport-business-magazine", "Airport Business Magazine"],
];

async function load(slug, file) {
  const p = path.join(KIT, slug, file);
  if (!fs.existsSync(p)) throw new Error(`missing ${p}: build the brand kit first (see the header of this script)`);
  const buf = await sharp(p).png({ compressionLevel: 9, palette: true }).toBuffer();
  const { width, height } = await sharp(buf).metadata();
  return { buf, width, height };
}

const entries = [];
for (const [slug, name] of TITLES) {
  const footer = await load(slug, "email-footer.png");
  const masthead = await load(slug, "email-masthead.png");
  entries.push(`  // ${name}
  "${slug}": {
    width: ${footer.width},
    height: ${footer.height},
    png: Buffer.from(
      "${footer.buf.toString("base64")}",
      "base64"
    ),
    mastheadWidth: ${masthead.width},
    mastheadHeight: ${masthead.height},
    masthead: Buffer.from(
      "${masthead.buf.toString("base64")}",
      "base64"
    ),
  },`);
  console.log(`${slug.padEnd(26)} footer ${footer.width}x${footer.height} (${(footer.buf.length / 1024).toFixed(1)}KB), masthead ${masthead.width}x${masthead.height} (${(masthead.buf.length / 1024).toFixed(1)}KB)`);
}

fs.writeFileSync(
  OUT,
  `// Per-title logos for the emails this app sends. Generated by
// scripts/build-brand-wordmarks.mjs from the brand kit in cogent-base-theme;
// do not edit by hand. Rerun the script when a title's logo changes or a title
// is added.
//
// png is the one-line mark for outreach sign-offs (drawn 22px high); masthead
// is the title's main mark for the top of the weekly newsletter.
export const WORDMARKS = {
${entries.join("\n")}
};

export function wordmarkFor(slug) {
  return WORDMARKS[slug] || null;
}

// How wide the newsletter should draw a masthead. A fixed width suits one
// shape and fails the rest: a stacked mark at 190px is tall and a long
// one-line mark is a sliver. Scaling by aspect gives every title about the
// same visual weight, within a sensible band.
export function mastheadDisplayWidth(mark) {
  if (!mark?.mastheadWidth || !mark?.mastheadHeight) return 190;
  const aspect = mark.mastheadWidth / mark.mastheadHeight;
  return Math.round(Math.min(280, Math.max(150, 62 * aspect)));
}
`
);
console.log(`wrote ${OUT}`);
