import { PrismaClient } from "@prisma/client";
import { decryptJson } from "../lib/crypto.js";
import { updatePost, fetchPost } from "../lib/wordpress.js";
const prisma = new PrismaClient();
const sites = await prisma.site.findMany({ select: { id: true, slug: true } });
const site = sites.find((s) => /smart/i.test(s.slug));
const rows = await prisma.siteCredential.findMany({ where: { siteId: site.id } });
const wp = Object.fromEntries(rows.map((r) => [r.kind, decryptJson(r.payloadEnc)])).wordpress;
await prisma.$disconnect();
const META = "Hugs & Co., the London footwear brand with soles stamped from scrap tyres, is exhibiting at Sweden's Bon Orbit gallery. What small firms can take from it.";
console.log("meta length:", META.length);
await updatePost(wp, 1026, { excerpt: META, meta: { _yoast_wpseo_metadesc: META } });
const post = await fetchPost(wp, 1026);
const html = post.content?.rendered ?? post.content?.raw ?? "";
console.log("title:   ", post.title?.rendered ?? post.title);
console.log("status:  ", post.status);
console.log("featured:", post.featured_media);
console.log("cats:    ", post.categories);
console.log("words:   ~" + html.replace(/<[^>]+>/g, " ").split(/\s+/).filter(Boolean).length);
console.log("em dashes in body:", /[—–]/.test(html));
console.log("yoast meta:", post.meta?._yoast_wpseo_metadesc);
console.log("keys:", Object.keys(post).join(","));
console.log("edit:    ", `https://smartsme.co.uk/wp-admin/post.php?post=1026&action=edit`);
